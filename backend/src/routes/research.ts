/**
 * Research-results API.
 *
 * The dashboard must not hardcode numbers: every value it displays is read from the
 * artifact produced by the corresponding script. If an artifact is missing, the field is
 * returned as null so the UI can say "not measured" instead of showing a stale figure.
 */
import { Router, type Request, type Response } from "express";
import { existsSync, readFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const REPO_ROOT = resolve(dirname(fileURLToPath(import.meta.url)), "..", "..", "..");

export const researchRouter = Router();

function readJson(relative: string): unknown | null {
  const path = resolve(REPO_ROOT, relative);
  if (!existsSync(path)) return null;
  try {
    return JSON.parse(readFileSync(path, "utf8"));
  } catch {
    return null;
  }
}

researchRouter.get("/research/results", (_req: Request, res: Response) => {
  const benchmarks = readJson("benchmarks/results/bench-hardhat.json");
  const costModel = readJson("benchmarks/results/l1-vs-l2-comparison.json");
  const ml = readJson("ml-service/models/metrics.json");
  const attacks = readJson("evaluation/results/attack-simulations.json");
  const coverage = readJson("coverage/coverage-summary.json");

  res.json({
    data: {
      benchmarks,
      costModel,
      ml,
      attacks,
      coverage,
      provenance: {
        benchmarks: {
          path: "benchmarks/results/bench-hardhat.json",
          label: "MEASURED on local Hardhat EVM (simulated network conditions)",
        },
        costModel: {
          path: "benchmarks/results/l1-vs-l2-comparison.json",
          label: "Cost model: locally measured gas x live/assumed gas price x assumed token price",
        },
        ml: {
          path: "ml-service/models/metrics.json",
          label: "Trained on a synthetic corpus; supervised scores measure synthetic signal recovery",
        },
        attacks: {
          path: "evaluation/results/attack-simulations.json",
          label: "SIMULATED protocol behaviour on the local EVM",
        },
        coverage: {
          path: "coverage/coverage-summary.json",
          label: "Solidity coverage generated by solidity-coverage",
        },
      },
      survey: {
        status: "NOT YET MEASURED",
        path: "evaluation/survey/survey_template.csv",
        detail: "No real pilot participants have been recruited. Synthetic responses are not findings.",
      },
    },
  });
});
